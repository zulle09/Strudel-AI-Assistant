/* Copy the web app into the Capacitor web directory, then write config.js.
 *
 * The web app has no build step - it is hand-written HTML, CSS and JS served
 * straight off disk - so there is nothing to bundle, only to copy. Capacitor
 * still wants its own webDir, and copying (rather than pointing webDir at
 * app/web) is what lets config.js exist for the app without also appearing in
 * the browser version, where the API is same-origin and the file would be
 * wrong.
 *
 * Set the backend URL with STRUDEL_API_BASE:
 *
 *     STRUDEL_API_BASE=http://192.168.1.20:8000 npm run sync
 *
 * A simulator can reach your Mac on http://localhost:8000; a real iPhone
 * needs the Mac's LAN address, and the backend must be started with
 * `--host 0.0.0.0` for it to answer.
 */

import { cp, rm, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "..", "app", "web");
const target = resolve(here, "www");

const apiBase = process.env.STRUDEL_API_BASE || "";
if (!apiBase) {
  console.warn(
    "[sync] STRUDEL_API_BASE is not set. The app will call its own origin,\n" +
      "       which inside the bundle has no backend. Set it before syncing."
  );
}

await rm(target, { recursive: true, force: true });
await mkdir(target, { recursive: true });
await cp(source, target, { recursive: true });

// Written into www rather than committed: it is generated from the
// environment at sync time, and its correct value differs per machine.
await writeFile(
  resolve(target, "config.js"),
  `/* Generated by sync-www.mjs. Do not edit; re-run \`npm run sync\`. */\n` +
    `window.STRUDEL_API_BASE = ${JSON.stringify(apiBase)};\n`
);

// The script tag is injected into the copy rather than committed to the
// source index.html, because /config.js does not exist when FastAPI serves
// the same page in a browser and a 404 on every page load is not worth it.
// It must precede app.js, which reads the global at parse time.
const indexPath = resolve(target, "index.html");
const html = await readFile(indexPath, "utf8");
const appTag = '<script src="/static/app.js"></script>';
if (!html.includes(appTag)) {
  throw new Error(
    `Could not find ${appTag} in index.html. The app shell changed; ` +
      "update the injection point in sync-www.mjs."
  );
}
await writeFile(
  indexPath,
  html.replace(appTag, `<script src="config.js"></script>\n${appTag}`)
);

console.log(`[sync] ${source}\n    -> ${target}`);
console.log(`[sync] API base: ${apiBase || "(same origin)"}`);
